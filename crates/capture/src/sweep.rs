//! A one-time snapshot of the client's state, taken with the first recording
//! of each client launch.
//!
//! The wire file only sees what changes during a recording. Things set before
//! champ select (queue config, owned champions, rank, lobby settings) never
//! change, so they'd be missing. The sweep GETs the endpoints of the plugins in
//! our spec subset that take no parameters (minus exclusions) and saves the
//! results, redacted, as compact JSON in `<name>.sweep.json` next to that
//! recording. Local only, like wire files. It uses its own redactor, so its
//! fakes don't match the recording's. Most of it is account state that doesn't
//! change between champ selects, so later recordings of the same launch don't
//! repeat it (see `extras`).
//!
//! The endpoint list is `sweep-paths.txt`, generated by `tools/lcu_spec.py`,
//! which also holds the exclusions (de-anonymizing, credentials, chat). Large
//! Clash endpoints ([`CLASH_ONLY`]) are fetched only in a Clash queue.

use std::future::Future;
use std::path::Path;

use lcu::LcuHttp;
use serde_json::{Map, Value, json};

use crate::fsutil;
use crate::redact::Redactor;

const PATHS: &str = include_str!("../sweep-paths.txt");

/// Endpoints the sweep requests.
pub fn paths() -> impl Iterator<Item = &'static str> {
    PATHS
        .lines()
        .map(str::trim)
        .filter(|l| !l.is_empty() && !l.starts_with('#'))
}

/// Clash endpoints too big to fetch when they can't matter: tournament
/// history is ~540 KB, the tournament list ~20 KB (16.22). The small Clash
/// endpoints stay in every sweep.
pub const CLASH_ONLY: &[&str] = &[
    "/lol-clash/v1/historyandwinners",
    "/lol-clash/v1/all-tournaments",
];

const GAMEFLOW_SESSION: &str = "/lol-gameflow/v1/session";

/// True if `/lol-gameflow/v1/session` is for a Clash queue. Not confirmed
/// against a Clash capture yet: matches a queue type containing `CLASH` or the
/// Clash queue IDs (700 Summoner's Rift, 720 ARAM). Unknown counts as Clash,
/// so a missing session never loses Clash data.
pub fn is_clash_queue(gameflow_session: Option<&Value>) -> bool {
    let Some(queue) = gameflow_session.and_then(|s| s.pointer("/gameData/queue")) else {
        return true;
    };
    let by_type = queue
        .get("type")
        .and_then(Value::as_str)
        .is_some_and(|t| t.to_ascii_uppercase().contains("CLASH"));
    let by_id = queue
        .get("id")
        .and_then(Value::as_i64)
        .is_some_and(|id| [700, 720].contains(&id));
    by_type || by_id
}

/// Outcome of one GET.
pub enum Fetched {
    Ok(Value),
    NotFound,
    Failed(String),
}

#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub struct SweepStats {
    pub ok: usize,
    pub not_found: usize,
    pub failed: usize,
    /// Left out on purpose (Clash-only outside a Clash queue).
    pub skipped: usize,
}

/// Fetches every path with `fetch` (one at a time, to go easy on the client)
/// and returns the redacted results keyed by path. The gameflow session, if
/// listed, is fetched first: it decides whether [`CLASH_ONLY`] paths are
/// fetched or marked skipped.
pub async fn collect<'a, F, Fut>(
    paths: impl IntoIterator<Item = &'a str>,
    mut fetch: F,
) -> (Value, SweepStats)
where
    F: FnMut(String) -> Fut,
    Fut: Future<Output = Fetched>,
{
    let mut paths: Vec<&str> = paths.into_iter().collect();
    if let Some(i) = paths.iter().position(|p| *p == GAMEFLOW_SESSION) {
        let p = paths.remove(i);
        paths.insert(0, p);
    }
    let mut redactor = Redactor::new();
    let mut results = Map::new();
    let mut stats = SweepStats {
        ok: 0,
        not_found: 0,
        failed: 0,
        skipped: 0,
    };
    let mut clash: Option<bool> = None;
    for path in paths {
        if CLASH_ONLY.contains(&path) {
            let in_clash = *clash.get_or_insert_with(|| {
                is_clash_queue(
                    results
                        .get(GAMEFLOW_SESSION)
                        .and_then(|e: &Value| e.get("data")),
                )
            });
            if !in_clash {
                stats.skipped += 1;
                results.insert(
                    path.to_string(),
                    json!({ "status": "skipped", "reason": "not a Clash queue" }),
                );
                continue;
            }
        }
        let entry = match fetch(path.to_string()).await {
            Fetched::Ok(mut data) => {
                stats.ok += 1;
                redactor.redact(&mut data);
                json!({ "status": "ok", "data": data })
            }
            Fetched::NotFound => {
                stats.not_found += 1;
                json!({ "status": "not_found" })
            }
            Fetched::Failed(error) => {
                stats.failed += 1;
                json!({ "status": "error", "error": error })
            }
        };
        results.insert(path.to_string(), entry);
    }
    (Value::Object(results), stats)
}

/// Runs the full sweep against the client and writes it to `dest`.
pub async fn run(http: &LcuHttp, dest: &Path) -> std::io::Result<SweepStats> {
    run_paths(http, dest, paths()).await
}

/// For later recordings of a client launch, whose full sweep was already
/// taken: if this is a Clash queue, sweeps just the gameflow session and the
/// [`CLASH_ONLY`] endpoints (the full sweep may have skipped them). `None`
/// when it's not Clash or the queue can't be read.
pub async fn run_clash_only(http: &LcuHttp, dest: &Path) -> std::io::Result<Option<SweepStats>> {
    let Ok(Some(session)) = http.get_json(GAMEFLOW_SESSION).await else {
        return Ok(None);
    };
    if !is_clash_queue(Some(&session)) {
        return Ok(None);
    }
    let paths = std::iter::once(GAMEFLOW_SESSION).chain(CLASH_ONLY.iter().copied());
    run_paths(http, dest, paths).await.map(Some)
}

async fn run_paths<'a>(
    http: &LcuHttp,
    dest: &Path,
    paths: impl IntoIterator<Item = &'a str>,
) -> std::io::Result<SweepStats> {
    let taken_at = jiff::Timestamp::now().to_string();
    let (results, stats) = collect(paths, |path| async move {
        match http.get_json(&path).await {
            Ok(Some(v)) => Fetched::Ok(v),
            Ok(None) => Fetched::NotFound,
            Err(e) => Fetched::Failed(e.to_string()),
        }
    })
    .await;
    let out = json!({
        "taken_at": taken_at,
        "client_version": http.client_version().await.ok(),
        "results": results,
    });
    // Compact: pretty-printing doubled the file. Pretty-print it to read it.
    let text = serde_json::to_vec(&out).expect("JSON values always serialize");
    fsutil::write_atomic(dest, &text).await?;
    Ok(stats)
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::redact::find_unredacted;

    #[test]
    fn path_list_is_sane() {
        let all: Vec<_> = paths().collect();
        assert!(all.len() > 50, "{}", all.len());
        for p in &all {
            assert!(p.starts_with("/lol-"), "{p}");
            assert!(!p.contains('{'), "{p}");
            for banned in [
                "obfuscated",
                "jwt",
                "token",
                "chat",
                "by-puuids",
                "muted",
                "custom-games",
            ] {
                assert!(!p.contains(banned), "{p} must be excluded");
            }
        }
        assert!(all.contains(&"/lol-champions/v1/owned-champions-minimal"));
        assert!(all.contains(&"/lol-lobby/v2/lobby"));
    }

    #[tokio::test]
    async fn results_are_redacted_and_counted() {
        let (results, stats) = collect(["/a", "/b", "/c"], |path| async move {
            match path.as_str() {
                "/a" => Fetched::Ok(json!({"puuid": "real", "queueId": 420})),
                "/b" => Fetched::NotFound,
                _ => Fetched::Failed("boom".into()),
            }
        })
        .await;
        assert_eq!(
            stats,
            SweepStats {
                ok: 1,
                not_found: 1,
                failed: 1,
                skipped: 0,
            }
        );
        assert_eq!(results["/a"]["data"]["queueId"], 420);
        assert_eq!(find_unredacted(&results), Vec::<String>::new());
        assert_eq!(results["/b"]["status"], "not_found");
        assert_eq!(results["/c"]["error"], "boom");
    }

    fn gameflow(queue: Value) -> Fetched {
        Fetched::Ok(json!({"gameData": {"queue": queue}}))
    }

    #[tokio::test]
    async fn clash_only_paths_are_skipped_outside_clash() {
        // The Clash path comes before the gameflow session in the list; the
        // session is still fetched first and decides.
        let paths = ["/lol-clash/v1/historyandwinners", GAMEFLOW_SESSION, "/x"];
        let (results, stats) = collect(paths, |path| async move {
            match path.as_str() {
                GAMEFLOW_SESSION => gameflow(json!({"id": 3130, "type": "NORMAL"})),
                "/lol-clash/v1/historyandwinners" => panic!("must not be fetched"),
                _ => Fetched::Ok(json!(1)),
            }
        })
        .await;
        assert_eq!((stats.ok, stats.skipped), (2, 1));
        assert_eq!(
            results["/lol-clash/v1/historyandwinners"]["status"],
            "skipped"
        );
    }

    #[tokio::test]
    async fn clash_only_paths_are_fetched_in_clash() {
        let paths = [GAMEFLOW_SESSION, "/lol-clash/v1/historyandwinners"];
        let (results, stats) = collect(paths, |path| async move {
            match path.as_str() {
                GAMEFLOW_SESSION => gameflow(json!({"id": 700, "type": "CLASH"})),
                _ => Fetched::Ok(json!({"history": []})),
            }
        })
        .await;
        assert_eq!((stats.ok, stats.skipped), (2, 0));
        assert_eq!(results["/lol-clash/v1/historyandwinners"]["status"], "ok");
    }

    #[test]
    fn clash_detection() {
        let s = |q: Value| json!({"gameData": {"queue": q}});
        assert!(is_clash_queue(Some(&s(json!({"id": 700})))));
        assert!(is_clash_queue(Some(&s(json!({"id": 720})))));
        assert!(is_clash_queue(Some(&s(
            json!({"id": 1, "type": "ARAM_CLASH"})
        ))));
        // Seen in 16.22 captures: ARAM (KIWI) and draft customs.
        assert!(!is_clash_queue(Some(&s(
            json!({"id": 2400, "type": "KIWI"})
        ))));
        assert!(!is_clash_queue(Some(&s(
            json!({"id": 3130, "type": "NORMAL"})
        ))));
        // No session: keep Clash data rather than risk losing it.
        assert!(is_clash_queue(None));
        assert!(is_clash_queue(Some(&json!({}))));
    }

    #[test]
    fn clash_only_paths_are_in_the_sweep_list() {
        let all: Vec<_> = paths().collect();
        for p in CLASH_ONLY {
            assert!(all.contains(p), "{p} isn't swept, so skipping it is moot");
        }
        assert!(all.contains(&GAMEFLOW_SESSION));
    }
}
