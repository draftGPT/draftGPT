//! A one-time snapshot of the client's state when a recording starts.
//!
//! The wire file only sees what changes during a recording. Things set before
//! champ select (queue config, owned champions, rank, lobby settings) never
//! change, so they'd be missing. The sweep GETs the endpoints of the plugins in
//! our spec subset that take no parameters (minus exclusions) once and saves
//! the results, redacted, as `<name>.sweep.json`. Local only, like wire files.
//! It uses its own redactor, so its fakes don't match the recording's.
//!
//! The endpoint list is `sweep-paths.txt`, generated by `tools/lcu_spec.py`,
//! which also holds the exclusions (de-anonymizing, credentials, chat).

use std::future::Future;
use std::path::Path;

use lcu::LcuHttp;
use serde_json::{Map, Value, json};

use crate::fsutil;
use crate::redact::Redactor;

const PATHS: &str = include_str!("../sweep-paths.txt");

/// Endpoints the sweep requests.
pub fn paths() -> impl Iterator<Item = &'static str> {
    PATHS
        .lines()
        .map(str::trim)
        .filter(|l| !l.is_empty() && !l.starts_with('#'))
}

/// Outcome of one GET.
pub enum Fetched {
    Ok(Value),
    NotFound,
    Failed(String),
}

#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub struct SweepStats {
    pub ok: usize,
    pub not_found: usize,
    pub failed: usize,
}

/// Fetches every path with `fetch` (one at a time, to go easy on the client)
/// and returns the redacted results keyed by path.
pub async fn collect<F, Fut>(
    paths: impl IntoIterator<Item = &str>,
    mut fetch: F,
) -> (Value, SweepStats)
where
    F: FnMut(String) -> Fut,
    Fut: Future<Output = Fetched>,
{
    let mut redactor = Redactor::new();
    let mut results = Map::new();
    let mut stats = SweepStats {
        ok: 0,
        not_found: 0,
        failed: 0,
    };
    for path in paths {
        let entry = match fetch(path.to_string()).await {
            Fetched::Ok(mut data) => {
                stats.ok += 1;
                redactor.redact(&mut data);
                json!({ "status": "ok", "data": data })
            }
            Fetched::NotFound => {
                stats.not_found += 1;
                json!({ "status": "not_found" })
            }
            Fetched::Failed(error) => {
                stats.failed += 1;
                json!({ "status": "error", "error": error })
            }
        };
        results.insert(path.to_string(), entry);
    }
    (Value::Object(results), stats)
}

/// Runs the sweep against the client and writes it to `dest`.
pub async fn run(http: &LcuHttp, dest: &Path) -> std::io::Result<SweepStats> {
    let taken_at = jiff::Timestamp::now().to_string();
    let (results, stats) = collect(paths(), |path| async move {
        match http.get_json(&path).await {
            Ok(Some(v)) => Fetched::Ok(v),
            Ok(None) => Fetched::NotFound,
            Err(e) => Fetched::Failed(e.to_string()),
        }
    })
    .await;
    let out = json!({
        "taken_at": taken_at,
        "client_version": http.client_version().await.ok(),
        "results": results,
    });
    let text = serde_json::to_vec_pretty(&out).expect("JSON values always serialize");
    fsutil::write_atomic(dest, &text).await?;
    Ok(stats)
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::redact::find_unredacted;

    #[test]
    fn path_list_is_sane() {
        let all: Vec<_> = paths().collect();
        assert!(all.len() > 50, "{}", all.len());
        for p in &all {
            assert!(p.starts_with("/lol-"), "{p}");
            assert!(!p.contains('{'), "{p}");
            for banned in [
                "obfuscated",
                "jwt",
                "token",
                "chat",
                "by-puuids",
                "muted",
                "custom-games",
            ] {
                assert!(!p.contains(banned), "{p} must be excluded");
            }
        }
        assert!(all.contains(&"/lol-champions/v1/owned-champions-minimal"));
        assert!(all.contains(&"/lol-lobby/v2/lobby"));
    }

    #[tokio::test]
    async fn results_are_redacted_and_counted() {
        let (results, stats) = collect(["/a", "/b", "/c"], |path| async move {
            match path.as_str() {
                "/a" => Fetched::Ok(json!({"puuid": "real", "queueId": 420})),
                "/b" => Fetched::NotFound,
                _ => Fetched::Failed("boom".into()),
            }
        })
        .await;
        assert_eq!(
            stats,
            SweepStats {
                ok: 1,
                not_found: 1,
                failed: 1
            }
        );
        assert_eq!(results["/a"]["data"]["queueId"], 420);
        assert_eq!(find_unredacted(&results), Vec::<String>::new());
        assert_eq!(results["/b"]["status"], "not_found");
        assert_eq!(results["/c"]["error"], "boom");
    }
}
